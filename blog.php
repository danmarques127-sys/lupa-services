      function initNavbarScroll() {
        const navbar = $("#navbar");
        if (!navbar) return;

        function updateNav() {
          const y = window.scrollY || window.pageYOffset;
          navbar.classList.toggle("isScrolled", y > 10);
        }

        updateNav();
        window.addEventListener("scroll", updateNav, { passive: true });
      }

      function initMobileMenu() {
        const navToggle = $("#navToggle");
        const mobileMenu = $("#mobileMenu");
        if (!navToggle || !mobileMenu) return;

        const close = () => {
          navToggle.classList.remove("isOpen");
          mobileMenu.classList.remove("isOpen");
          navToggle.setAttribute("aria-expanded", "false");
          mobileMenu.setAttribute("aria-hidden", "true");
          document.body.style.overflow = "";
        };

        const open = () => {
          navToggle.classList.add("isOpen");
          mobileMenu.classList.add("isOpen");
          navToggle.setAttribute("aria-expanded", "true");
          mobileMenu.setAttribute("aria-hidden", "false");
          document.body.style.overflow = "hidden";
        };

        navToggle.addEventListener("click", () => {
          const isOpen = navToggle.classList.contains("isOpen");
          isOpen ? close() : open();
        });

        $$("[data-close]", mobileMenu).forEach((item) => {
          item.addEventListener("click", close);
        });

        window.addEventListener("keydown", (e) => {
          if (e.key === "Escape") close();
        });

        window.addEventListener("resize", () => {
          if (window.innerWidth > 920) close();
        });
      }

      function initReveal() {
        const items = $$(".reveal");
        if (!items.length) return;

        if ("IntersectionObserver" in window) {
          const io = new IntersectionObserver((entries) => {
            entries.forEach((entry) => {
              if (entry.isIntersecting) {
                entry.target.classList.add("isIn");
                io.unobserve(entry.target);
              }
            });
          }, { threshold: 0.12 });

          items.forEach((item) => io.observe(item));
        } else {
          items.forEach((item) => item.classList.add("isIn"));
        }
      }

      function initCounterAnimation() {
        const counters = $$("[data-count]");
        if (!counters.length) return;

        const animateCounter = (el) => {
          const target = Number(el.dataset.count || 0);
          const duration = 1400;
          const start = performance.now();

          const frame = (now) => {
            const progress = Math.min((now - start) / duration, 1);
            const eased = 1 - Math.pow(1 - progress, 3);
            const current = Math.round(target * eased);
            el.textContent = current;

            if (progress < 1) {
              requestAnimationFrame(frame);
            }
          };

          requestAnimationFrame(frame);
        };

        if ("IntersectionObserver" in window) {
          const io = new IntersectionObserver((entries) => {
            entries.forEach((entry) => {
              if (entry.isIntersecting) {
                animateCounter(entry.target);
                io.unobserve(entry.target);
              }
            });
          }, { threshold: 0.4 });

          counters.forEach((counter) => io.observe(counter));
        } else {
          counters.forEach(animateCounter);
        }
      }

      function initNotifyForm() {
        const form = $("#notifyForm");
        const input = $("#notifyEmail");
        const msg = $("#notifyMsg");
        if (!form || !input || !msg) return;

        form.addEventListener("submit", (e) => {
          e.preventDefault();

          const value = input.value.trim();
          const valid = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(value);

          if (!valid) {
            input.focus();
            input.style.borderColor = "rgba(255,90,90,.65)";
            return;
          }

          input.style.borderColor = "rgba(255,255,255,.10)";
          form.reset();
          msg.classList.add("is-show");

          setTimeout(() => {
            msg.classList.remove("is-show");
          }, 4200);
        });
      }

      function initNewsletterForm() {
        const form = $("#newsletterForm");
        const msg = $("#newsletterMsg");
        if (!form || !msg) return;

        form.addEventListener("submit", (e) => {
          e.preventDefault();
          msg.classList.remove("hidden");
          form.reset();
        });
      }
    })();
